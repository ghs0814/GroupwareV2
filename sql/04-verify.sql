SELECT SYS_CONTEXT('USERENV','CON_NAME') AS SERVICE_NAME FROM DUAL;
SELECT TABLE_NAME FROM USER_TABLES ORDER BY TABLE_NAME;
SELECT 'EMPLOYEE' AS TABLE_NAME,COUNT(*) AS ROW_COUNT FROM EMPLOYEE
UNION ALL SELECT 'ROOM',COUNT(*) FROM ROOM
UNION ALL SELECT 'EQUIPMENT',COUNT(*) FROM EQUIPMENT
UNION ALL SELECT 'BOARD',COUNT(*) FROM BOARD
UNION ALL SELECT 'BOARD_COMMENT',COUNT(*) FROM BOARD_COMMENT
UNION ALL SELECT 'RESERVATION',COUNT(*) FROM RESERVATION
UNION ALL SELECT 'RENTAL_HISTORY',COUNT(*) FROM RENTAL_HISTORY
UNION ALL SELECT 'LEAVE_HISTORY',COUNT(*) FROM LEAVE_HISTORY;
SELECT TRIGGER_NAME,STATUS FROM USER_TRIGGERS ORDER BY TRIGGER_NAME;
SELECT OBJECT_NAME,OBJECT_TYPE,STATUS FROM USER_OBJECTS WHERE STATUS <> 'VALID';
SELECT EQ_NO,TOTAL_COUNT,REMAIN_COUNT FROM EQUIPMENT WHERE REMAIN_COUNT<0 OR REMAIN_COUNT>TOTAL_COUNT;
SELECT EMP_NO,CUR_LEAVE FROM EMPLOYEE WHERE CUR_LEAVE<0;
