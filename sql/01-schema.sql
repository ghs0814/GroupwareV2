-- ==========================================
-- 2. 테이블 생성 (정규화 및 제약조건 포함)
-- ==========================================

-- 1. 사원 테이블 (EMPLOYEE)
CREATE TABLE EMPLOYEE (
    EMP_NO NUMBER PRIMARY KEY,
    EMP_PW VARCHAR2(200 CHAR),
    EMP_NAME VARCHAR2(50 CHAR) NOT NULL,
    EMP_LEVEL NUMBER NOT NULL,
    MANAGER VARCHAR2(1 CHAR) DEFAULT 'N',
    DEPT VARCHAR2(50 CHAR),
    MAX_LEAVE NUMBER DEFAULT 15,
    CUR_LEAVE NUMBER DEFAULT 15,
    RETIRED VARCHAR2(1 CHAR) DEFAULT 'N',
    TEMP_LEVEL NUMBER DEFAULT 0,
    CONSTRAINT CK_EMP_MANAGER CHECK (MANAGER IN ('Y', 'N')),
    CONSTRAINT CK_EMP_RETIRED CHECK (RETIRED IN ('Y', 'N'))
);

-- 2. 회의실 테이블 (ROOM)
CREATE TABLE ROOM (
    ROOM_ID VARCHAR2(20 CHAR) PRIMARY KEY,
    ROOM_NAME VARCHAR2(100 CHAR) NOT NULL,
    CAPACITY NUMBER DEFAULT 0,
    HAS_BEAM VARCHAR2(1 CHAR) DEFAULT 'N',
    DESCRIPTION VARCHAR2(500 CHAR),
    ENABLE VARCHAR2(1 CHAR) DEFAULT 'Y' NOT NULL,
    CONSTRAINT CK_ROOM_BEAM CHECK (HAS_BEAM IN ('Y', 'N')),
    CONSTRAINT CK_ROOM_ENABLE CHECK (ENABLE IN ('Y', 'N'))
);

-- 3. 비품 마스터 테이블 (EQUIPMENT)
CREATE TABLE EQUIPMENT (
    EQ_NO NUMBER PRIMARY KEY,
    EQ_NAME VARCHAR2(100 CHAR) NOT NULL,
    TOTAL_COUNT NUMBER DEFAULT 0,
    REMAIN_COUNT NUMBER DEFAULT 0,
    ISCHECKED CHAR(1 CHAR) DEFAULT 'Y' NOT NULL
);

-- 4. 예약 테이블 (RESERVATION)
CREATE TABLE RESERVATION (
    RES_NO NUMBER PRIMARY KEY,
    EMP_NO NUMBER NOT NULL REFERENCES EMPLOYEE(EMP_NO),
    ROOM_ID VARCHAR2(20 CHAR) NOT NULL REFERENCES ROOM(ROOM_ID),
    RES_DATE DATE NOT NULL,
    START_TIME VARCHAR2(10 CHAR) NOT NULL,
    END_TIME VARCHAR2(10 CHAR) NOT NULL,
    PURPOSE VARCHAR2(200 CHAR),
    STATUS VARCHAR2(20 CHAR) DEFAULT '예약완료',
    EXPIRE_TIME TIMESTAMP
);

-- 5. 비품 대여 이력 테이블 (RENTAL_HISTORY)
CREATE TABLE RENTAL_HISTORY (
    RENTAL_NO NUMBER PRIMARY KEY,
    EMP_NO NUMBER NOT NULL REFERENCES EMPLOYEE(EMP_NO),
    EQ_NO NUMBER NOT NULL REFERENCES EQUIPMENT(EQ_NO),
    TITLE VARCHAR2(200 CHAR),
    REQ_COUNT NUMBER DEFAULT 1,
    RENTAL_DATE DATE NOT NULL,
    RETURN_DATE DATE NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT '승인대기',
    APPROVAL_STEP NUMBER DEFAULT 1,
    SIGN1 VARCHAR2(100 CHAR), SIGN1_DATE DATE,
    SIGN2 VARCHAR2(100 CHAR), SIGN2_DATE DATE,
    SIGN3 VARCHAR2(100 CHAR), SIGN3_DATE DATE,
    SIGN4 VARCHAR2(100 CHAR), SIGN4_DATE DATE,
    SIGN5 VARCHAR2(100 CHAR), SIGN5_DATE DATE,
    REASON VARCHAR2(500 CHAR)
);

-- 6. 휴가 신청 이력 테이블 (LEAVE_HISTORY)
CREATE TABLE LEAVE_HISTORY (
    LEAVE_NO NUMBER PRIMARY KEY,
    EMP_NO NUMBER NOT NULL REFERENCES EMPLOYEE(EMP_NO),
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    USE_DAYS NUMBER NOT NULL,
    REASON VARCHAR2(500 CHAR),
    STATUS VARCHAR2(20 CHAR) DEFAULT '승인대기',
    APPROVAL_STEP NUMBER DEFAULT 1,
    SIGN1 VARCHAR2(100 CHAR), SIGN1_DATE DATE,
    SIGN2 VARCHAR2(100 CHAR), SIGN2_DATE DATE,
    SIGN3 VARCHAR2(100 CHAR), SIGN3_DATE DATE,
    SIGN4 VARCHAR2(100 CHAR), SIGN4_DATE DATE,
    SIGN5 VARCHAR2(100 CHAR), SIGN5_DATE DATE
);

-- 7. 게시판 테이블 (BOARD)
CREATE TABLE BOARD (
    BOARD_NO NUMBER PRIMARY KEY,
    BOARD_TYPE NUMBER NOT NULL, 
    TITLE VARCHAR2(200 CHAR) NOT NULL,
    CONTENT CLOB NOT NULL,
    EMP_NO NUMBER NOT NULL,
    REG_DATE DATE DEFAULT SYSDATE,
    HIT NUMBER DEFAULT 0,
    CONSTRAINT FK_BOARD_EMP FOREIGN KEY (EMP_NO) REFERENCES EMPLOYEE(EMP_NO)
);

-- 8. 게시판 첨부파일 테이블 (BOARD_FILE)
CREATE TABLE BOARD_FILE (
    FILE_NO NUMBER PRIMARY KEY,
    BOARD_NO NUMBER NOT NULL,
    ORG_NAME VARCHAR2(300 CHAR) NOT NULL,
    SAVED_NAME VARCHAR2(300 CHAR) NOT NULL,
    FILE_SIZE NUMBER DEFAULT 0,
    CONSTRAINT FK_FILE_BOARD FOREIGN KEY (BOARD_NO) REFERENCES BOARD(BOARD_NO) ON DELETE CASCADE
);

-- 9. 게시판 댓글 테이블 (BOARD_COMMENT)
CREATE TABLE BOARD_COMMENT (
    COMMENT_NO NUMBER PRIMARY KEY,
    BOARD_NO NUMBER NOT NULL,
    EMP_NO NUMBER NOT NULL,
    CONTENT VARCHAR2(1000 CHAR) NOT NULL,
    REG_DATE DATE DEFAULT SYSDATE,
    PARENT_NO NUMBER, 
    GROUP_NO NUMBER NOT NULL, 
    ORDER_NO NUMBER DEFAULT 0, 
    DEPTH NUMBER DEFAULT 0, 
    CONSTRAINT FK_COMMENT_BOARD FOREIGN KEY (BOARD_NO) REFERENCES BOARD(BOARD_NO) ON DELETE CASCADE,
    CONSTRAINT FK_COMMENT_EMP FOREIGN KEY (EMP_NO) REFERENCES EMPLOYEE(EMP_NO),
    CONSTRAINT FK_COMMENT_PARENT FOREIGN KEY (PARENT_NO) REFERENCES BOARD_COMMENT(COMMENT_NO) ON DELETE CASCADE
);

-- 10. 휴가 이력 백업 테이블 (LEAVE_HISTORY_BACKUP)
CREATE TABLE LEAVE_HISTORY_BACKUP (
    BACKUP_ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BACKUP_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ACTION_TYPE VARCHAR(10 CHAR),
    LEAVE_NO INT,
    EMP_NO INT,
    START_DATE DATE,
    END_DATE DATE,
    USE_DAYS INT,
    REASON VARCHAR(500 CHAR),
    STATUS VARCHAR(50 CHAR),
    APPROVAL_STEP INT,
    SIGN1 VARCHAR(100 CHAR), SIGN1_DATE DATE,
    SIGN2 VARCHAR(100 CHAR), SIGN2_DATE DATE,
    SIGN3 VARCHAR(100 CHAR), SIGN3_DATE DATE,
    SIGN4 VARCHAR(100 CHAR), SIGN4_DATE DATE,
    SIGN5 VARCHAR(100 CHAR), SIGN5_DATE DATE
);

-- 11. 비품 대여 이력 백업 테이블 (RENTAL_HISTORY_BACKUP)
CREATE TABLE RENTAL_HISTORY_BACKUP (
    BACKUP_ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BACKUP_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ACTION_TYPE VARCHAR(10 CHAR),
    RENTAL_NO INT,
    EMP_NO INT,
    EQ_NO INT,
    TITLE VARCHAR(200 CHAR),
    REQ_COUNT INT,
    RENTAL_DATE DATE,
    RETURN_DATE DATE,
    STATUS VARCHAR(50 CHAR),
    APPROVAL_STEP INT,
    SIGN1 VARCHAR(100 CHAR), SIGN1_DATE DATE,
    SIGN2 VARCHAR(100 CHAR), SIGN2_DATE DATE,
    SIGN3 VARCHAR(100 CHAR), SIGN3_DATE DATE,
    SIGN4 VARCHAR(100 CHAR), SIGN4_DATE DATE,
    SIGN5 VARCHAR(100 CHAR), SIGN5_DATE DATE,
    REASON VARCHAR(500 CHAR)
);

