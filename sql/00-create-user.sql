WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET VERIFY OFF
SET SERVEROUTPUT ON
ACCEPT project_password CHAR PROMPT 'New GROUPWARE_BOOT password: ' HIDE

-- Run as SYSTEM connected to ORCLPDB1, not CDB$ROOT.
DECLARE
    user_count NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV','CON_NAME') <> 'ORCLPDB1' THEN
        RAISE_APPLICATION_ERROR(-20001,'Connect SYSTEM to ORCLPDB1 first.');
    END IF;
    SELECT COUNT(*) INTO user_count FROM ALL_USERS WHERE USERNAME='GROUPWARE_BOOT';
    IF user_count=0 THEN
        EXECUTE IMMEDIATE 'CREATE USER GROUPWARE_BOOT IDENTIFIED BY "&&project_password" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA 50M ON USERS';
        EXECUTE IMMEDIATE 'GRANT CREATE SESSION,CREATE TABLE,CREATE SEQUENCE,CREATE TRIGGER TO GROUPWARE_BOOT';
        DBMS_OUTPUT.PUT_LINE('GROUPWARE_BOOT created.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Account already exists; no password or grants were changed.');
    END IF;
END;
/
UNDEFINE project_password
