CREATE OR REPLACE TRIGGER TRG_LEAVE_BACKUP
AFTER INSERT OR UPDATE ON LEAVE_HISTORY
FOR EACH ROW
DECLARE
    v_action VARCHAR2(10);
BEGIN
    IF INSERTING THEN v_action := 'INSERT'; ELSE v_action := 'UPDATE'; END IF;
    INSERT INTO LEAVE_HISTORY_BACKUP (ACTION_TYPE,LEAVE_NO,EMP_NO,START_DATE,END_DATE,USE_DAYS,REASON,STATUS,APPROVAL_STEP,SIGN1,SIGN1_DATE,SIGN2,SIGN2_DATE,SIGN3,SIGN3_DATE,SIGN4,SIGN4_DATE,SIGN5,SIGN5_DATE)
    VALUES (v_action,:NEW.LEAVE_NO,:NEW.EMP_NO,:NEW.START_DATE,:NEW.END_DATE,:NEW.USE_DAYS,:NEW.REASON,:NEW.STATUS,:NEW.APPROVAL_STEP,:NEW.SIGN1,:NEW.SIGN1_DATE,:NEW.SIGN2,:NEW.SIGN2_DATE,:NEW.SIGN3,:NEW.SIGN3_DATE,:NEW.SIGN4,:NEW.SIGN4_DATE,:NEW.SIGN5,:NEW.SIGN5_DATE);
END;
/
SHOW ERRORS

